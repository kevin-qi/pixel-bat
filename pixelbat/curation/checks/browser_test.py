"""Drive the curation page in a headless browser on a throwaway copy of a sort: browser_test.py http://localhost:PORT/?sort=SORT SHOT_DIR.

Runs the main interactions, asserts what each must do, times them, and saves a screenshot per step.
"""
import sys

from playwright.sync_api import sync_playwright

SHELL = '/home/kevin/.cache/ms-playwright/chromium_headless_shell-1248/chrome-headless-shell-linux64/chrome-headless-shell'
url, shots = sys.argv[1], sys.argv[2]
failures = []


def check(name, condition):
    print(f'  {"ok  " if condition else "FAIL"} {name}')
    if not condition:
        failures.append(name)


with sync_playwright() as p:
    browser = p.chromium.launch(executable_path=SHELL)
    page = browser.new_page(viewport={'width': 1900, 'height': 1100})
    errors = []
    page.on('pageerror', lambda e: errors.append(str(e)))
    page.on('console', lambda m: errors.append(m.text) if m.type == 'error' else None)
    state = lambda expression: page.evaluate(expression)
    settle = lambda: page.evaluate('S.queue.then(() => new Promise(r => requestAnimationFrame(() => requestAnimationFrame(r))))')

    def step(name):
        settle()
        page.screenshot(path=f'{shots}/{name}.png')
        print(f'{name}: status "{page.inner_text("#status")}" | errors {errors}')

    def timed(label, action):
        """Milliseconds from an action until the page has redrawn."""
        ms = page.evaluate("""async (run) => { const t = performance.now(); eval(run); await S.queue;
                              await new Promise(r => requestAnimationFrame(() => requestAnimationFrame(r))); return performance.now() - t; }""", action)
        print(f'  {label}: {ms:.0f} ms')

    def key(k):
        page.keyboard.press(k)
        settle()

    page.goto(url)
    page.wait_for_function("document.getElementById('loading').style.display === 'block'")
    page.screenshot(path=f'{shots}/00_loading.png')
    check('a loading card says what is being waited for', 'app:' in page.inner_text('#stepApp') and 'unit data' in page.inner_text('#stepArrays'))
    page.wait_for_function("typeof S !== 'undefined' && !S.loading && S.lines.length > 0 && S.canvases.size > 0", timeout=120000)
    check('the loading card goes when the sort is drawn', state("document.getElementById('loading').style.display") == 'none')
    print(f'  page usable after {state("performance.now()"):.0f} ms')
    check('no merge group under 500 spikes is listed', state("S.groups.every(g => g.section !== 'groups' || g.units.reduce((sum, id) => sum + unitOf(id).n_spikes, 0) >= 500)"))
    check('a fresh browser opens at the top, on the first merge group', state('list.scrollTop') == 0 and state("S.lines[focusIndex()].type") == 'group')
    first = state("S.lines.find(l => l.type === 'group' && l.units.length === 2).units.map(u => u.unit)")
    state(f"select({first}, {first[0]}); scrollToFocus()")
    step('01_group_selected')
    check('a group click selects all its units', state('S.sel.length') == 2)
    y = state("S.lines[focusIndex()].y - list.scrollTop + list.getBoundingClientRect().top + S.lines[focusIndex()].head + 40")
    page.mouse.click(700, y); settle()
    check('clicking a row of a selected group selects that unit only', state('S.sel') == [first[0]])
    page.mouse.click(700, y - 70); settle()
    check('clicking the group header selects the group again', state('S.sel.length') == 2)
    page.mouse.click(22, y + 0); settle()
    check('the tick box of a row removes it from the selection', state('S.sel') == [first[1]])
    page.mouse.click(22, y + 0); settle()
    check('and adds it back', sorted(state('S.sel')) == sorted(first))
    page.mouse.move(700, y); settle()
    check('hovering a row of the selected group shades that row', state("hover.style.display") == 'block' and state("hover.offsetHeight") == state('ROW'))
    timed('next group (j)', "press('j')"); timed('previous group (k)', "press('k')")
    check('the group verdict is one of Kilosort\'s three', state("together(S.sel.map(unitOf), S.lines[focusIndex()].group.pairs).pairs[0].verdict") in ['refractory', 'untestable', 'not refractory'])
    check('the decision strip has four cells: Kilosort, Bombcell, this tool, you', state("(() => { const cells = strip(S.lines[focusIndex()].group, S.sel.map(unitOf)); return cells.length === 4 && cells[0][0][0] === 'Kilosort: ' && cells[1][0][0] === 'Bombcell if merged: ' && cells[2][0][0] === 'this tool: ' && cells[3][0][0] === 'you: '; })()"))
    key('2')
    check('a digit on the whole group selects that row alone', state('S.sel') == [first[1]])
    key('1')
    check('the next digit adds its row', sorted(state('S.sel')) == sorted(first))
    key('1'); key('1')
    check('but never removes the last unit', state('S.sel') == [first[0]])
    key('2')
    check('and adds it back', state('S.sel') == first)
    timed('single spikes (w)', "press('w')")
    page.wait_for_function("S.sel.every(id => S.traces.get(S.rowOf.get(id)))")
    step('02_spikes')
    check('w shows single spikes, loaded once per unit', state('S.view') == 'spikes' and state('S.traces.size') >= 2)
    timed('density (w)', "press('w')")
    step('02_density')
    key('w')
    check('w cycles back to the mean', state('S.view') == 'mean')
    # Merge, label, unmerge
    page.keyboard.press('Shift+M'); page.keyboard.press('g')   # no wait between: the label must land on the merged unit
    step('03_merged_then_good')
    merged = state("S.units.filter(u => u.members.length > 1).map(u => [u.unit, u.label, u.section])")
    check('merge then g labels the merged unit good', merged == [[merged[0][0], 'good', 'groups']] if merged else False)
    check('the two original units are gone', state(f"S.byId.has({first[0]})") is False)
    state(f"select([{merged[0][0]}], {merged[0][0]}); scrollToFocus()")
    page.click('#list button'); settle()
    step('04_unmerged')
    check('unmerge restores the units', state(f"S.byId.has({first[0]}) && S.byId.has({first[1]})"))
    check('unmerge selects the group again', sorted(state('S.sel')) == sorted(first))
    # Keep apart is retired: no button, and x does nothing
    check('no keep-apart button', state("document.getElementById('keep') === null"))
    state(f"select({first}, {first[0]}); scrollToFocus()"); events = state('S.nEvents'); key('x')
    check('x writes nothing', state('S.nEvents') == events)
    # Labels in place, no label
    state(f"select([{first[0]}], {first[0]})"); key('g')
    check('a label leaves the selection where it is', state('S.sel') == [first[0]] and state(f"unitOf({first[0]}).label") == 'good')
    state(f"select([{first[1]}], {first[1]})"); key('g')
    check('both members labelled one by one', state(f"unitOf({first[1]}).label") == 'good' and state('S.sel') == [first[1]])
    state(f"select([{first[0]}], {first[0]})"); key('Shift+F')
    check('shift+F flags the unit in place', state(f"unitOf({first[0]}).flagged") and state(f"unitOf({first[0]}).section") == 'groups')
    key('Shift+F')
    check('flag again removes the mark', not state(f"unitOf({first[0]}).flagged"))
    page.keyboard.press('/'); page.keyboard.type(str(first[1])); page.keyboard.press('Enter'); settle()
    check('go to unit selects it', state('S.sel') == [first[1]])
    before_repeat = state('S.nEvents')
    page.evaluate("document.dispatchEvent(new KeyboardEvent('keydown', {key: 'n', code: 'KeyN', repeat: true}))"); settle()
    check('a held-down decision key does not repeat', state('S.nEvents') == before_repeat)
    key('e')
    check('e goes to the next undecided item', state("S.sel.some(id => !unitOf(id).label)"))
    check('labelled units stay in the merge group section', state(f"unitOf({first[0]}).section") == 'groups')
    state(f"select({first}, {first[0]})"); key('Backspace')
    check('backspace removes the labels', state(f"unitOf({first[0]}).label") is None)
    step('05_kept_apart')
    second = state("S.lines.filter(l => l.type === 'group' && l.units.length === 2 && openGroup(l.group))[1].units.map(u => u.unit)")
    state(f"select({second}, {second[0]}); scrollToFocus()")
    key('Shift+F'); key('Shift+F')
    events = state('S.nEvents'); key('n')
    check('one press labels a whole undecided group, keeps it apart and labels each unit', state(f"S.groups.find(g => g.units.includes({second[0]})).kept") and state(f"unitOf({second[1]}).label") == 'noise')
    check('as one decision', state('S.nEvents') == events + 1)
    key('z')
    check('undo returns to what it changed', second[0] in state('S.sel') and state(f"unitOf({second[1]}).label") is None)
    # Caps Lock: M without shift is mua, never merge
    state(f"select({first}, {first[0]}); scrollToFocus()")
    page.evaluate("document.dispatchEvent(new KeyboardEvent('keydown', {key: 'M', code: 'KeyM', shiftKey: false}))"); settle()
    check('M without shift labels mua and does not merge', state(f"unitOf({first[0]}) && unitOf({first[0]}).label") == 'mua')
    key('z')
    check('undo says what it undid', 'undid' in page.inner_text('#status') or 'undone' in page.inner_text('#status'))
    # Help swallows the key that closes it
    state(f"select({first}, {first[0]}); scrollToFocus()"); key('?'); key('n')
    check('other keys leave help open and do nothing', state("document.getElementById('help').style.display") == 'block' and state(f"unitOf({first[0]}).label") is None)
    key('Escape')
    check('Esc closes help', state("document.getElementById('help').style.display") == 'none')
    # Tiles: select, move, label, accept a screen
    state("list.scrollTop = S.lines.find(l => l.type === 'tiles' && l.section === 'good').y - 40"); settle()
    page.mouse.click(400, 250); settle()
    tile = state('S.sel')
    check('a tile click selects one tile', len(tile) == 1)
    # Ctrl+click adds or removes one tile; shift+click selects the span in list order
    box = state("(() => { const l = S.lines.find(l => l.type === 'tiles' && l.section === 'good' && l.units.length > 2); const r = list.getBoundingClientRect(); return [r.left, r.top + l.y - list.scrollTop, S.tileW, l.units.map(u => u.unit)]; })()")
    page.mouse.click(box[0] + 0.5 * box[2], box[1] + 60); settle()
    page.keyboard.down('Control'); page.mouse.click(box[0] + 2.5 * box[2], box[1] + 60); page.keyboard.up('Control'); settle()
    check('ctrl+click adds one tile', sorted(state('S.sel')) == sorted([box[3][0], box[3][2]]))
    page.keyboard.down('Control'); page.mouse.click(box[0] + 2.5 * box[2], box[1] + 60); page.keyboard.up('Control'); settle()
    check('ctrl+click again removes it', state('S.sel') == [box[3][0]])
    page.keyboard.down('Shift'); page.mouse.click(box[0] + 2.5 * box[2], box[1] + 60); page.keyboard.up('Shift'); settle()
    check('shift+click selects every tile of the span', state('S.sel') == box[3][:3])
    # A section header selects the whole section; one key labels it all, undo takes it back
    head = state("(() => { const i = S.lines.findIndex(l => l.type === 'header' && l.section === 'good'); list.scrollTop = S.lines[i].y; drawList(); return list.getBoundingClientRect().top + 10; })()"); settle()
    page.mouse.click(300, head); settle()
    check('a section header selects every unit of the section', len(state('S.sel')) == state("S.units.filter(u => u.section === 'good').length"))
    step('06_section_selected')
    events = state('S.nEvents'); key('m')
    check('one key labels the whole section in one decision', state("S.units.filter(u => u.section === 'good').every(u => u.label === 'mua')") and state('S.nEvents') == events + 1)
    key('z')
    # Remaining only: labelled units leave the list, the counts stay
    state(f"select([{tile[0]}], {tile[0]}); scrollToFocus()"); key('g')
    shown = lambda: state(f"S.lines.some(l => l.units.some(u => u.unit === {tile[0]}))")
    key('h')
    check('h hides labelled units', state('S.remaining') and not shown() and state("S.lines.every(l => l.units.every(u => !u.label) || l.type === 'group')"))
    key('h')
    check('h again shows them', not state('S.remaining') and shown())
    key('z')
    state(f"select([{tile[0]}], {tile[0]}); scrollToFocus()")
    key('ArrowRight')
    check('arrow right moves to the next tile', state('S.sel') != tile and len(state('S.sel')) == 1)
    step('06_tile')
    timed('tile click', "document.querySelector('#list canvas[data-index]') && select([S.lines.find(l => l.type === 'tiles').units[2].unit])")
    before = state("S.units.filter(u => u.label).length")
    timed('accept screen (a)', "press('a')")
    step('07_accepted')
    check('accept screen labels tiles', state("S.units.filter(u => u.label).length") > before)
    check('accept screen says what it did', 'units →' in page.inner_text('#status'))
    key('z')
    check('undo removes them', state("S.units.filter(u => u.label).length") == before)
    # A merge of units outside any group, then unmerge by its button
    pair = state("S.lines.find(l => l.type === 'tiles' && l.section === 'good').units.slice(0, 2).map(u => u.unit)")
    state(f"select({pair}, {pair[0]}); scrollToFocus()"); key('Shift+M')
    made = state("S.sel[0]")
    check('a merge of two tiles stays in their section, selected', state(f"unitOf({made}).section") == 'good' and state('S.focusUnit') == made and state(f"unitOf({made}).members.length") == 2)
    step('08_adhoc_merge')
    key('Shift+U')
    check('shift+U unmerges it', state(f"S.byId.has({pair[0]})") and sorted(state('S.sel')) == sorted(pair))
    # Amplitude floor on one unit: spikes below it leave the unit; undo restores them
    state(f"select([{pair[0]}], {pair[0]}); scrollToFocus()")
    page.wait_for_function(f"S.amps.has({pair[0]})")
    before_floor = state(f"unitOf({pair[0]}).n_spikes")
    state(f"S.floorDraft = {{unit: {pair[0]}, floor: [...S.amps.get({pair[0]})].sort((a, b) => a - b)[Math.floor({before_floor} * 0.2)]}}")
    key('t')
    after_floor = state(f"unitOf({pair[0]}).n_spikes")
    check('an amplitude floor sets aside the spikes below it', 0.75 * before_floor < after_floor < 0.85 * before_floor and state(f"spikeTrain(unitOf({pair[0]})).length") == after_floor)
    key('z')
    check('undo removes the floor', state(f"unitOf({pair[0]}).n_spikes") == before_floor and state(f"spikeTrain(unitOf({pair[0]})).length") == before_floor)
    # A stale page cannot decide
    other = browser.new_page(viewport={'width': 1900, 'height': 1100})
    other.goto(url)
    other.wait_for_function("typeof S !== 'undefined' && !S.loading && S.lines.length > 0 && S.canvases.size > 0", timeout=120000)
    state(f"select([{pair[0]}], {pair[0]}); scrollToFocus()"); key('g')
    other.evaluate(f"select([{pair[0]}], {pair[0]}); scrollToFocus()"); other.keyboard.press('n')
    other.evaluate('S.queue.then(() => new Promise(r => requestAnimationFrame(r)))')
    check('a stale page is refused and told why', 'out of date' in other.inner_text('#status'))
    check('and it is brought up to date', other.evaluate(f"unitOf({pair[0]}).label") == 'good')
    other.keyboard.press('j'); other.evaluate('S.queue')
    check('its keys still work afterwards', other.evaluate('S.sel.length') >= 1)
    other.close()
    key('z')
    # Depth order keeps the place; dark mode
    state(f"select({first}, {first[0]})")
    page.click('#menu summary'); page.check('#depth'); settle()
    check('depth order keeps the focused unit on screen', state("(l => l.y >= list.scrollTop - 5 && l.y < list.scrollTop + list.clientHeight)(S.lines[focusIndex()])"))
    step('09_depth_order')
    page.uncheck('#depth'); settle()
    page.click('#dark'); settle()
    state(f"select({first}, {first[0]}); scrollToFocus()")
    key('s')
    check('+ similar adds reference units that are not selected', state('S.ref.length') == 3 and state('S.sel.length') == 2)
    step('10_dark_similar')
    page.click('#dark'); page.click('#menu summary')
    # Few spikes: the last section, its label on f
    check('few spikes is the last section', state("S.lines.filter(l => l.type === 'header').map(l => l.section).pop()") == 'few')
    check('a unit under 500 spikes is few spikes without a decision', state("S.units.filter(u => u.n_spikes < 500 && !u.label).length") == 0
          and state("S.units.filter(u => u.auto_few).every(u => u.label === 'few')"))
    other = state("S.units.find(u => u.section === 'good' && !u.label).unit")
    state(f"show([{other}])"); key('f')
    check('f labels a unit few spikes', state(f"unitOf({other}).label") == 'few')
    key('z')
    several = state("S.units.filter(u => u.section === 'good' && !u.label).slice(0, 3).map(u => u.unit)")
    state(f"show({several})"); events = state('S.nEvents'); key('m')
    check('one press labels several selected units', all(state(f"unitOf({u}).label") == 'mua' for u in several) and state('S.nEvents') == events + 1)
    key('z')
    # Possible merges: the section after the merge groups, p, and a merge that the search follows
    check('the top bar gives the outcome and what is left', 'outcome:' in page.inner_text('#outcome') and 'to review' in page.inner_text('#left'))
    check('the possible merges section follows the merge groups', state("SECTIONS.map(([s]) => s).slice(0, 2).join() === 'groups,possible' && S.lines.filter(l => l.type === 'header').map(l => l.section).slice(0, 2).join() === 'groups,possible'"))
    possible = state("S.groups.filter(g => g.section === 'possible').map(g => g.units)")
    check('possible merges are listed', len(possible) > 0)
    state(f"show([{possible[0][0]}])"); key('p')
    check('p adds the best partner for reference', len(state('S.ref')) == 1 and state('S.sel') == [possible[0][0]])
    key('p')
    check('p again adds the next', len(state('S.ref')) == 2)
    key('Escape')
    key('g')
    check('labelling one unit of a possible pair decides it, and it stays listed', state(f"S.groups.some(g => g.section === 'possible' && g.units.join() === '{','.join(map(str, possible[0]))}' && !openGroup(g))"))
    key('z')
    check('the pair line carries the hand-off', state("S.groups.flatMap(g => Object.values(g.pairs)).every(p => typeof p.handoff === 'number')"))
    state(f"(() => {{ const i = S.lines.findIndex(l => l.type === 'group' && l.group.units.join() === '{','.join(map(str, possible[0]))}'); selectLine(i); scrollToFocus(); }})()")
    key('Shift+M')
    after = state("S.groups.filter(g => g.section === 'possible').map(g => g.units)")
    check('a merged possible pair leaves the section, which is searched again', possible[0] not in after and state("unitOf(S.sel[0]).members.length") == 2)
    step('12_possible_merged')
    key('z')
    check('undo brings the pair back', state("S.groups.filter(g => g.section === 'possible').map(g => g.units)") == possible)
    check('every merge group carries the four decision cells', state("S.groups.filter(g => g.units.length > 1).every(g => strip(g, g.units.map(unitOf)).length === 4)"))
    big = state("[...S.units].sort((a, b) => b.n_spikes - a.n_spikes).slice(0, 5).map(u => u.unit)")
    timed('select 5 largest units', f"select({big})")
    step('11_five_largest')
    # Open dialog
    sort = state('S.name')
    page.click('#open')
    page.wait_for_function("document.getElementById('folders').children.length > 0")
    step('13_open_dialog')
    check('Open lists the folder holding the sort', page.input_value('#path') == sort.rsplit('/', 1)[0])
    check('the open sort is listed as a prepared sort', state("[...document.querySelectorAll('#folders .entry')].some(e => e.children[0].textContent === S.name.split('/').pop() && e.children[1].textContent === 'prepared sort')"))
    check('the recent sorts include this one, marked as the open one', state("[...document.querySelectorAll('#known tbody tr')].some(r => S.name.endsWith(r.children[0].textContent) && r.className === 'current')"))
    page.fill('#filter', 'no-such-sort')
    check('the filter narrows the recent sorts', state("document.querySelectorAll('#known tbody tr').length") == 0)
    page.fill('#filter', sort.rsplit('/', 1)[1])
    check('to those whose path has its words', state("[...document.querySelectorAll('#known tbody tr')].some(r => S.name.endsWith(r.children[0].textContent))"))
    page.fill('#filter', '')
    page.click('#known th[data-by=decisions]')
    counts = state("[...document.querySelectorAll('#known tbody tr')].map(r => +r.children[3].textContent).filter(n => !Number.isNaN(n))")
    check('a column header orders the list by that column', counts == sorted(counts, reverse=True))
    page.fill('#path', sort + '/curation')
    page.keyboard.press('Enter')
    page.wait_for_function("document.getElementById('path').value.endsWith('/curation') && document.getElementById('folders').children.length > 0 && [...document.getElementById('folders').children].some(e => e.textContent.startsWith('cache'))")
    check('a folder that is not a sort is listed, with no prepare command', state("document.getElementById('folderNote').textContent") == '' and state("document.getElementById('opener').style.display") == 'block')
    page.fill('#path', sort)
    page.keyboard.press('Enter')
    page.wait_for_function("document.getElementById('opener').style.display === 'none' && !S.loading")
    settle()
    check('a prepared sort typed into the dialog opens, with its decisions', state('S.name') == sort and state('S.nEvents') > 0)
    check('the address names the sort', state('new URLSearchParams(location.search).get("sort")') == sort)
    browser.close()
print(f'{len(failures)} checks failed: {failures}' if failures else 'all checks passed', '| page errors:', errors)
